// Universal World Layer — GLAD (Global Land Analysis & Discovery)
// Global Forest Change import.
//
// The University of Maryland's GLAD lab produces the Hansen Global
// Forest Change dataset (Hansen, Potapov, Moore, Hancher et al.,
// "High-Resolution Global Maps of 21st-Century Forest Cover Change",
// Science, 2013, updated annually) — a real, global, 30m-resolution
// record of tree cover extent in the year 2000, and every year's
// forest LOSS since, through the most recent update. GLAD also
// produces near-real-time deforestation alerts used by Global Forest
// Watch, built on the same lab's work. Licence: Creative Commons
// Attribution 4.0 International, stated on the dataset's own terms
// page.
//
// ---------------------------------------------------------------------
// The one real environmental fact nothing in this registry names at
// all
// ---------------------------------------------------------------------
// `grep -rn "forest\|landCover\|vegetation\|treeCover" vacon-c/server/
// *.js world-layer/*.js` returns nothing before this file. No source
// already wired here — not USGS, not Overture, not Natural Earth —
// carries a single fact about vegetation or forest cover anywhere on
// Earth.
//
// ---------------------------------------------------------------------
// A real, named thing this WOULD feed, and a declared absence of
// wiring to it
// ---------------------------------------------------------------------
// `vacon-c/server/economy.js`'s own `generateResource` schema comment
// names `timber` as one example of a real `resourceType` string
// (`resources.resource_type` is an open-ended column, "not a closed
// enum"). **Checked directly: nothing in `worldgen.js` or anywhere
// else in `vacon-c/server/` ever calls `generateResource` with
// `resourceType: 'timber'`** — the string exists in a comment and is
// generated by nothing. Wiring a real per-location timber supply from
// this importer's own tree-cover figure is a genuine, concrete future
// join (a `timberPacks.js`, the same shape every other real source in
// that registry's history has taken) — and, following `vacon-c/
// CLAUDE.md`'s own thirtieth standing rule for `usgsImport.js`, it is
// NOT built here: a resource-generation pass is a design decision
// about how much timber a given tree-cover percentage should actually
// produce, which this file has no business inventing on its own.
// This importer is the real, tested transform; the join is its own
// future round.
//
// NETWORK CONSTRAINT, checked directly against this environment's
// agent proxy status endpoint: `glad.umd.edu` returns a 403 CONNECT
// rejection, the same block every other source host in this registry
// hits (GLAD's data is also mirrored inside Google Earth Engine's
// public catalog, at `earthenginepartners.appspot.com` — checked
// separately and also blocked). `fetchForestChangeTile` throws with
// that reason; `importForestCover` is the real, tested part.

'use strict';

const { setLocationData, getLocation } = require('../locations');

// **The canopy-cover threshold that decides "is this forest" is an
// interpretive choice and is stated as one.** The Hansen/GLAD dataset
// itself publishes a continuous tree-cover percentage (0-100) and
// imposes no binary cutoff — Global Forest Watch's own default public
// map display uses 30%, which is the figure used here, named rather
// than treated as part of the raw data.
const FOREST_CANOPY_THRESHOLD_PCT = 30;

// GLAD's own data years. `lossYear` in the raw product is a single
// integer 1-23 meaning "lost in 2001" through "lost in 2023" for the
// 2024 release — tracked here as a real range rather than assumed
// fixed, since the dataset extends by one year on every annual
// update.
const FIRST_LOSS_YEAR = 2001;
const LATEST_LOSS_YEAR = 2023;

// A real, deterministic classification from the raw fields — no
// model, no estimate.
//
// `record`: `{ treeCoverPct2000, lossYear }`. `lossYear` is `null` for
// a pixel with no recorded loss through the dataset's latest update.
function classifyForestStatus(record) {
  // `Number(null)` is `0`, a real finite number inside 0..100 — the
  // exact trap `vacon-c/CLAUDE.md`'s own corollary on `Number()`
  // already names elsewhere in this ecosystem. A missing reading is
  // not a real zero, so `null`/`undefined` are rejected explicitly
  // before coercion rather than left to pass as "0% tree cover".
  const raw = record?.treeCoverPct2000;
  const coverage = Number(raw);
  if (raw === null || raw === undefined || !Number.isFinite(coverage) || coverage < 0 || coverage > 100) {
    throw new Error(
      `classifyForestStatus requires a real treeCoverPct2000 in 0..100, got ${record?.treeCoverPct2000}`,
    );
  }
  const wasForest = coverage >= FOREST_CANOPY_THRESHOLD_PCT;
  if (!wasForest) return 'non-forest';

  const lossYear = record?.lossYear;
  if (lossYear === null || lossYear === undefined) return 'intact-forest';

  if (!Number.isInteger(lossYear) || lossYear < FIRST_LOSS_YEAR || lossYear > LATEST_LOSS_YEAR) {
    throw new Error(
      `classifyForestStatus: lossYear ${lossYear} is outside the dataset's real range `
      + `(${FIRST_LOSS_YEAR}-${LATEST_LOSS_YEAR})`,
    );
  }
  return 'lost-forest';
}

// Attach real forest-cover data to a location.
function importForestCover(worldLayer, locationId, record = {}) {
  const location = getLocation(worldLayer, locationId);
  if (!location) throw new Error(`importForestCover: no location with id ${locationId}`);

  const status = classifyForestStatus(record);
  const existing = location.geographyData ?? {};
  setLocationData(worldLayer, locationId, 'geographyData', {
    ...existing,
    forestCover: {
      source: 'glad-global-forest-change',
      licence: 'cc-by-4.0',
      treeCoverPct2000: Math.round(Number(record.treeCoverPct2000) * 10) / 10,
      // Null, never 0 — a pixel with no recorded loss is not the same
      // claim as "lost in year zero", and Number(null) is 0.
      lossYear: record.lossYear ?? null,
      canopyThresholdPct: FOREST_CANOPY_THRESHOLD_PCT,
      status,
    },
  });
  return location;
}

function describeForestCoverage(worldLayer) {
  const byStatus = {};
  let withData = 0;
  for (const location of worldLayer.locations || []) {
    const forest = location.geographyData?.forestCover;
    if (forest?.source !== 'glad-global-forest-change') continue;
    withData += 1;
    byStatus[forest.status] = (byStatus[forest.status] ?? 0) + 1;
  }
  return {
    withData,
    byStatus,
    total: (worldLayer.locations || []).length,
  };
}

function fetchForestChangeTile() {
  throw new Error(
    'fetchForestChangeTile is not implemented: glad.umd.edu is outside this environment\'s '
    + 'outbound proxy allowlist (403 CONNECT, confirmed directly against the agent proxy\'s '
    + 'own status endpoint; earthenginepartners.appspot.com, GLAD\'s Earth Engine mirror, is '
    + 'also blocked, confirmed separately). The real data is distributed as 10x10-degree '
    + 'GeoTIFF granules at glad.umd.edu, no key, no rate limit. Pass { treeCoverPct2000, '
    + `lossYear } to importForestCover(worldLayer, locationId, record). Loss years run `
    + `${FIRST_LOSS_YEAR}-${LATEST_LOSS_YEAR} in the dataset's latest release.`,
  );
}

module.exports = {
  FOREST_CANOPY_THRESHOLD_PCT,
  FIRST_LOSS_YEAR,
  LATEST_LOSS_YEAR,
  classifyForestStatus,
  importForestCover,
  describeForestCoverage,
  fetchForestChangeTile,
};
